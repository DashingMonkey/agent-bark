        let dir = std::env::temp_dir().join(format!("agent-bark-oc-{}", uuid::Uuid::new_v4().simple()));
        let ours_dir = dir.join("agent-bark");
        std::fs::create_dir_all(&ours_dir).unwrap();
        let file = ours_dir.join("opencode-plugin.js");
        let entry = json!(file.to_string_lossy().replace('/', "\\"));

        // 含生成标记 → 认领
        std::fs::write(&file, "// Generated by agent-bark. Do not edit.\n").unwrap();
        assert!(OpenCodeAdapter::entry_matches(&entry), "含标记的同形文件是我们的");

        // 用户自己的同形插件（可读、无标记）→ 不认领：register 不得改写它、
